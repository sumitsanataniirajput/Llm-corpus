/* ========================================
   CORPUS ULTIMATE — AI Chat

   Messages are generated by the deployed inference endpoint only. If the
   model is missing or generation fails, the UI says so — it never invents a
   reply. Conversation history is stored locally per account.
   ======================================== */

window.chat = (function () {
  'use strict';

  const STORAGE_KEY = 'corpus_chat_sessions_v1';
  const MAX_SESSIONS = 30;

  let sessions = [];
  let currentId = null;
  let isGenerating = false;
  let abortController = null;
  // Mutable so the model selector can update Send/Enter without a full repaint.
  let activeModel = null;

  function esc(value) {
    return ui.escapeHtml(value == null ? '' : String(value));
  }

  function storageKey() {
    const user = state.getUser();
    return STORAGE_KEY + ':' + ((user && (user.id || user.email)) || 'anonymous');
  }

  function loadSessions() {
    try {
      const raw = window.localStorage ? window.localStorage.getItem(storageKey()) : null;
      const parsed = raw ? JSON.parse(raw) : [];
      sessions = Array.isArray(parsed) ? parsed : [];
    } catch (e) {
      sessions = [];
    }
  }

  function persistSessions() {
    try {
      if (!window.localStorage) return;
      window.localStorage.setItem(storageKey(), JSON.stringify(sessions.slice(0, MAX_SESSIONS)));
    } catch (e) {
      // Storage full or disabled — in-memory history still works.
    }
  }

  function newSession() {
    const session = {
      id: 'chat_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
      title: 'New conversation',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      messages: [],
    };
    sessions.unshift(session);
    currentId = session.id;
    persistSessions();
    renderConversationList();
    renderMessages();
    return session;
  }

  function currentSession() {
    return sessions.find(session => session.id === currentId) || null;
  }

  async function render() {
    const user = state.getUser();
    const container = window.CORPUS_APP.getPageContainer();
    if (!container) return;
    if (!user) {
      container.innerHTML = ui.emptyState({
        icon: 'fa-user-circle',
        title: 'Sign in required',
        text: 'Please sign in to chat with your trained models.',
        actionLabel: 'Sign in',
        actionOnclick: "auth.openModal('login')",
        actionIcon: 'fa-sign-in-alt',
      });
      return;
    }

    loadSessions();
    await state.ensureModels();
    activeModel = state.getActiveModel();
    if (!currentId && sessions.length) currentId = sessions[0].id;
    const modelOptions = state.getModels().map((model) => {
      const label = (model.name || model.id) + (model.status === 'trained' ? ' · trained' : ' · no checkpoint');
      return `<option value="${esc(model.id)}" ${activeModel && activeModel.id === model.id ? 'selected' : ''}>${esc(label)}</option>`;
    }).join('');

    container.innerHTML = `
      <div class="page-header">
        <div class="page-header-copy">
          <span class="eyebrow"><i class="fas fa-comments"></i> Inference</span>
          <h1 class="section-title">AI Chat</h1>
          <p class="section-subtitle">Responses are generated from your selected model's trained weights through the backend inference API.</p>
        </div>
        <div class="page-header-actions">
          <button class="btn btn-outline" type="button" onclick="chat.toggleSidebar()" aria-label="Toggle conversation history">
            <i class="fas fa-clock-rotate-left"></i> History
          </button>
          <button class="btn btn-primary" type="button" onclick="chat.startNew()">
            <i class="fas fa-plus"></i> New chat
          </button>
        </div>
      </div>

      <div id="chat-no-model" class="info-panel${activeModel ? ' hidden' : ''}" style="margin-bottom:var(--space-4);">
        <i class="fas fa-circle-info"></i>
        <div><strong>No model selected.</strong> Choose a model above, or open <a href="#/models" onclick="event.preventDefault();router.navigate('models')">Models</a> to train one. Sending is disabled until a model is active.</div>
      </div>

      <div class="chat-container">
        <aside class="chat-sidebar" id="chat-sidebar" aria-label="Conversation history">
          <div class="chat-header">
            <h3>Conversations</h3>
            <button class="icon-btn" type="button" onclick="chat.startNew()" aria-label="New conversation">
              <i class="fas fa-plus"></i>
            </button>
          </div>
          <div class="chat-list" id="chat-list"></div>
          <div style="padding:var(--space-2) var(--space-3); border-top:1px solid var(--color-border);">
            <p class="field-hint" style="margin:0;">History is stored on this device for your account.</p>
          </div>
        </aside>

        <div class="chat-main">
          <div class="chat-header">
            <button class="icon-btn" type="button" onclick="chat.toggleSidebar()" aria-label="Show conversation history" style="margin-right:var(--space-1);">
              <i class="fas fa-bars"></i>
            </button>
            <label class="chat-model-select-label" for="chat-model-select">Model</label>
            <select id="chat-model-select" class="chat-model-select"
                    inputmode="none" enterkeyhint="done" autocapitalize="off" spellcheck="false"
                    aria-label="Select model for chat" onchange="chat.selectModel(this.value)">
              <option value="" ${activeModel ? '' : 'selected'}>No model selected</option>
              ${modelOptions}
            </select>
            <span id="chat-model-readiness" class="status-badge ${activeModel && activeModel.status === 'trained' ? 'completed' : 'cancelled'}">
              ${activeModel ? esc(activeModel.status === 'trained' ? 'Checkpoint ready' : 'No checkpoint') : 'No model selected'}
            </span>
            <span class="spacer"></span>
            <button class="btn btn-ghost btn-sm" type="button" onclick="chat.clearCurrent()" title="Delete this conversation">
              <i class="fas fa-trash"></i>
            </button>
          </div>

          <div class="chat-messages" id="chat-messages" aria-live="polite"></div>

          <details class="chat-settings-details" style="border-top:1px solid var(--color-border);">
            <summary class="chat-settings-summary" style="cursor:pointer; list-style:none; padding:var(--space-2) var(--space-4); font-size:var(--text-label-small); color:var(--color-text-muted); display:flex; align-items:center; gap:var(--space-2);">
              <i class="fas fa-sliders"></i> Sampling settings
            </summary>
            <div class="chat-settings" id="chat-settings">
              <div class="chat-setting-row">
                <span class="chat-setting-label">Temperature</span>
                <input type="range" id="chat-temp" min="0" max="2" step="0.1" value="0.8" class="slider">
                <span class="chat-setting-value" id="chat-temp-val">0.8</span>
              </div>
              <div class="chat-setting-row">
                <span class="chat-setting-label">Top-K</span>
                <input type="number" id="chat-topk" value="50" min="1" step="1" inputmode="numeric" enterkeyhint="done" autocapitalize="off" spellcheck="false">
              </div>
              <div class="chat-setting-row">
                <span class="chat-setting-label">Top-P</span>
                <input type="range" id="chat-topp" min="0" max="1" step="0.05" value="0.9" class="slider">
                <span class="chat-setting-value" id="chat-topp-val">0.9</span>
              </div>
              <div class="chat-setting-row">
                <span class="chat-setting-label">Max tokens</span>
                <input type="number" id="chat-maxtokens" value="100" min="1" step="1" inputmode="numeric" enterkeyhint="done" autocapitalize="off" spellcheck="false">
              </div>
            </div>
          </details>

          <div class="chat-input-area">
            <textarea id="chat-input" class="chat-input" rows="1" inputmode="text"
                      enterkeyhint="send" autocapitalize="sentences" spellcheck="true"
                      aria-label="Message your model"
                      placeholder="Message your model… (Enter to send, Shift+Enter for a new line)"></textarea>
            <button class="chat-send" id="chat-send" type="button" onclick="chat.sendMessage()" disabled
                    ${activeModel ? '' : 'title="Select a model first"'}>
              <i class="fas fa-paper-plane"></i>
            </button>
          </div>
        </div>
      </div>
    `;

    wireComposer();
    renderConversationList();
    renderMessages();
  }

  function selectModel(modelId) {
    const model = modelId ? state.getModel(modelId) : null;
    activeModel = model || null;
    state.setActiveModel(activeModel);
    const selector = document.getElementById('chat-model-select');
    if (selector) selector.value = activeModel ? activeModel.id : '';
    const readiness = document.getElementById('chat-model-readiness');
    if (readiness) {
      readiness.className = 'status-badge ' + (activeModel && activeModel.status === 'trained' ? 'completed' : 'cancelled');
      readiness.textContent = activeModel
        ? (activeModel.status === 'trained' ? 'Checkpoint ready' : 'No checkpoint')
        : 'No model selected';
    }
    const warning = document.getElementById('chat-no-model');
    if (warning) warning.classList.toggle('hidden', !!activeModel);
    const input = document.getElementById('chat-input');
    const send = document.getElementById('chat-send');
    if (send) send.disabled = !activeModel || isGenerating || !(input && input.value.trim());
  }

  function wireComposer() {
    const temp = document.getElementById('chat-temp');
    const topp = document.getElementById('chat-topp');
    const input = document.getElementById('chat-input');
    if (temp) temp.addEventListener('input', (e) => {
      const val = document.getElementById('chat-temp-val');
      if (val) val.textContent = e.target.value;
    });
    if (topp) topp.addEventListener('input', (e) => {
      const val = document.getElementById('chat-topp-val');
      if (val) val.textContent = e.target.value;
    });
    if (!input) return;

    const autoGrow = () => {
      input.style.height = 'auto';
      input.style.height = Math.min(input.scrollHeight, 128) + 'px';
    };
    input.addEventListener('input', (e) => {
      autoGrow();
      const send = document.getElementById('chat-send');
      if (send) send.disabled = !e.target.value.trim() || isGenerating || !activeModel;
    });
    input.addEventListener('keydown', (e) => {
      if (e.key !== 'Enter' || e.shiftKey) return;
      // Indic and other Android IMEs emit Enter (isComposing / keyCode 229)
      // while a candidate word is still being composed. Sending then would
      // submit half a word, swallow the keystroke and drop the caret.
      if (e.isComposing || e.keyCode === 229) return;
      // With no usable model we let Enter insert a normal newline: the field
      // stays editable, only Send is disabled (with an explanation).
      if (!activeModel || isGenerating) return;
      e.preventDefault();
      sendMessage();
    });
    autoGrow();
  }

  function renderConversationList() {
    const container = document.getElementById('chat-list');
    if (!container) return;
    if (!sessions.length) {
      container.innerHTML = '<p class="field-hint" style="padding:var(--space-3); margin:0;">No conversations yet. Start one below.</p>';
      return;
    }
    container.innerHTML = sessions.map(session => `
      <div class="chat-list-item ${session.id === currentId ? 'active' : ''}" onclick="chat.openConversation('${esc(session.id)}')" role="button" tabindex="0">
        <span class="chat-avatar"><i class="fas fa-comment" style="font-size:0.7rem;"></i></span>
        <div class="chat-list-text">
          <div class="chat-list-title">${esc(session.title || 'Conversation')}</div>
          <div class="chat-list-meta">${esc(ui.timeAgo(session.updatedAt || session.createdAt))}</div>
        </div>
      </div>
    `).join('');
  }

  function emptyChatMarkup() {
    const activeModel = state.getActiveModel();
    const suggestions = ['Summarise what you were trained on.', 'Write a short paragraph about your topic.', 'Continue this sentence: The corpus contains'];
    return `
      <div class="empty-state" style="border:1px dashed var(--color-border);">
        <i class="fas fa-comments"></i>
        <h3>${activeModel ? 'Start a conversation' : 'Select a model to begin'}</h3>
        <p>${activeModel
          ? 'Messages go to the inference endpoint for ' + esc(activeModel.name || activeModel.id) + '. Replies depend entirely on how that model was trained.'
          : 'Pick a model on the Models page, then come back to chat with it.'}</p>
        <div class="chip-row" style="justify-content:center; margin-top:var(--space-4);">
          ${suggestions.map(text => `<button class="chip" type="button" onclick="chat.insertPrompt(${JSON.stringify(text).replace(/"/g, '&quot;')})">${esc(text)}</button>`).join('')}
        </div>
      </div>
    `;
  }

  function renderMessages() {
    const container = document.getElementById('chat-messages');
    if (!container) return;
    const session = currentSession();
    if (!session || !session.messages.length) {
      container.innerHTML = emptyChatMarkup();
      return;
    }
    container.innerHTML = session.messages.map((message, index) => messageMarkup(message, index)).join('');
    container.scrollTop = container.scrollHeight;
  }

  function messageMarkup(message, index) {
    const isUser = message.role === 'user';
    return `
      <div class="chat-message ${isUser ? 'user' : 'ai'}" data-index="${index}">
        <div class="chat-message-head">${isUser ? 'You' : 'CORPUS'}</div>
        <div class="chat-message-content ${message.error ? 'is-error' : ''}">${renderContent(message.text)}</div>
        <div class="chat-message-time">${esc(message.at ? new Date(message.at).toLocaleTimeString() : '')}</div>
        <div class="msg-actions">
          ${ui.copyButton(message.text, 'Copy')}
        </div>
      </div>
    `;
  }

  // Minimal, safe markdown: fenced code blocks, inline code, bold, line breaks.
  function renderContent(text) {
    const raw = String(text == null ? '' : text);
    const codeBlocks = [];
    let html = esc(raw).replace(/```([a-zA-Z0-9+#-]*)\n?([\s\S]*?)```/g, (match, lang, code) => {
      const token = '@@CODE' + codeBlocks.length + '@@';
      const language = (lang || 'code').toLowerCase();
      codeBlocks.push(
        '<div class="chat-code">' +
          '<div class="chat-code-head"><span>' + esc(language) + '</span>' +
          ui.copyButton(code.replace(/\n$/, ''), 'Copy') + '</div>' +
          '<pre><code>' + code.replace(/\n$/, '') + '</code></pre>' +
        '</div>'
      );
      return token;
    });
    html = html.replace(/`([^`\n]+)`/g, '<code class="mono">$1</code>');
    html = html.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
    html = html.replace(/@@CODE(\d+)@@/g, (match, i) => codeBlocks[Number(i)] || '');
    return html;
  }

  function openConversation(id) {
    const session = sessions.find(item => item.id === id);
    if (!session) return;
    currentId = id;
    renderConversationList();
    renderMessages();
    const sidebar = document.getElementById('chat-sidebar');
    if (sidebar) sidebar.classList.remove('is-open');
  }

  function toggleSidebar() {
    const sidebar = document.getElementById('chat-sidebar');
    if (sidebar) sidebar.classList.toggle('is-open');
  }

  function startNew() {
    if (isGenerating) {
      ui.toast('Wait for the current response to finish.', 'info');
      return;
    }
    newSession();
    const input = document.getElementById('chat-input');
    if (input) input.focus();
  }

  function insertPrompt(text) {
    const input = document.getElementById('chat-input');
    if (!input) return;
    input.value = text;
    input.dispatchEvent(new Event('input'));
    input.focus();
  }

  function clearCurrent() {
    const session = currentSession();
    if (!session) {
      ui.toast('No conversation to delete.', 'info');
      return;
    }
    ui.confirm('Delete conversation', 'Remove this conversation from this device? This cannot be undone.', () => {
      sessions = sessions.filter(item => item.id !== session.id);
      currentId = sessions.length ? sessions[0].id : null;
      persistSessions();
      renderConversationList();
      renderMessages();
      ui.toast('Conversation deleted', 'success');
    });
  }

  function setSending(sending) {
    const send = document.getElementById('chat-send');
    const input = document.getElementById('chat-input');
    isGenerating = sending;
    if (send) {
      send.disabled = sending || !input || !input.value.trim();
      send.innerHTML = sending
        ? '<i class="fas fa-circle-notch fa-spin"></i>'
        : '<i class="fas fa-paper-plane"></i>';
    }
    // The composer is never disabled — not while a response is streaming and
    // not when no model is selected. Only the Send action is gated.
    if (input) input.disabled = false;
  }

  async function sendMessage() {
    if (isGenerating) return;
    const input = document.getElementById('chat-input');
    if (!input) return;
    const text = input.value.trim();
    if (!text) return;

    const activeModel = state.getActiveModel();
    if (!activeModel) {
      ui.toast('Select a model before sending a message.', 'error');
      return;
    }

    let session = currentSession();
    if (!session) session = newSession();

    session.messages.push({ role: 'user', text: text, at: new Date().toISOString() });
    if (session.messages.length === 1) {
      session.title = text.slice(0, 48) + (text.length > 48 ? '…' : '');
    }
    session.updatedAt = new Date().toISOString();
    persistSessions();
    renderConversationList();

    input.value = '';
    input.style.height = 'auto';
    setSending(true);
    renderMessages();

    const messagesEl = document.getElementById('chat-messages');
    const pending = document.createElement('div');
    pending.className = 'chat-message ai';
    pending.innerHTML = '<div class="chat-message-head">CORPUS</div>' +
      '<div class="chat-message-content"><i class="fas fa-circle-notch fa-spin"></i> Generating from ' + esc(activeModel.name || activeModel.id) + '…</div>';
    messagesEl.appendChild(pending);
    messagesEl.scrollTop = messagesEl.scrollHeight;

    abortController = new AbortController();
    try {
      const payload = {
        text: text,
        temperature: parseFloat((document.getElementById('chat-temp') || {}).value) || 0.8,
        top_k: parseInt((document.getElementById('chat-topk') || {}).value, 10) || 50,
        top_p: parseFloat((document.getElementById('chat-topp') || {}).value) || 0.9,
        max_tokens: parseInt((document.getElementById('chat-maxtokens') || {}).value, 10) || 100,
      };
      const token = await state.getAccessToken();
      const result = await window.CORPUS_API.infer(activeModel.id, payload, token);
      if (result && result.status === 'unavailable') {
        throw new Error(result.message || 'This model has no trained checkpoint yet.');
      }
      const response = result && (result.response || result.text);
      if (!response || !String(response).trim()) {
        throw new Error('The backend returned an empty response. The model may not be trained yet.');
      }
      session.messages.push({ role: 'ai', text: String(response), at: new Date().toISOString() });
      session.updatedAt = new Date().toISOString();
      persistSessions();
      renderMessages();
      renderConversationList();
      // The reply is visible above; this confirms the backend answered at all,
      // and is deduplicated so a streamed duplicate cannot double-notify.
      ui.toast('Chat response received!', 'success', 1800);
    } catch (err) {
      const message = 'Error: ' + (err && err.message ? err.message : 'Generation failed');
      session.messages.push({ role: 'ai', text: message, at: new Date().toISOString(), error: true });
      session.updatedAt = new Date().toISOString();
      persistSessions();
      renderMessages();
      ui.toast(err && err.message ? err.message : 'Generation failed', 'error');
    } finally {
      abortController = null;
      setSending(false);
      if (input) {
        input.disabled = false;
        input.focus();
      }
      const send = document.getElementById('chat-send');
      if (send) send.disabled = !(input && input.value.trim());
      if (messagesEl) messagesEl.scrollTop = messagesEl.scrollHeight;
    }
  }

  return { render, selectModel, sendMessage, openConversation, startNew, toggleSidebar, insertPrompt, clearCurrent };
})();
